"""Section 7: experiment design with a power calculation on measured baselines."""
import math

import pandas as pd
from statsmodels.stats.power import NormalIndPower
from statsmodels.stats.proportion import proportion_effectsize

from src import config

# Twelve most recent complete months: volume for the duration estimate.
VOLUME_WINDOW = ("2017-07-01", "2018-07-01")
ALLOCATION = 0.5   # 50/50 split


def n_per_arm_proportion(p_control, relative_drop):
    p_treat = p_control * (1 - relative_drop)
    es = abs(proportion_effectsize(p_control, p_treat))   # Cohen's h
    n = NormalIndPower().solve_power(effect_size=es, alpha=config.ALPHA, power=config.POWER,
                                     ratio=1.0, alternative="two-sided")
    return math.ceil(n), p_treat


def n_per_arm_mean(sd, delta):
    n = NormalIndPower().solve_power(effect_size=delta / sd, alpha=config.ALPHA, power=config.POWER,
                                     ratio=1.0, alternative="two-sided")
    return math.ceil(n)


def main(con, m):
    v0, v1 = VOLUME_WINDOW
    one = lambda s: con.execute(s).fetchone()[0]
    in_w = f"purchase_date >= date '{v0}' and purchase_date < date '{v1}'"
    base = {
        # Eligible population = late orders (the trigger fires when an order runs late).
        "late_orders_per_month": one(f"select count(*) / 12.0 from mart_promise_gap where is_late and {in_w}"),
        "late_reviewed_per_month": one(
            f"select count(*) / 12.0 from mart_promise_gap where is_late and has_review and {in_w}"),
        "late_first_observed_per_month": one(
            f"select count(*) / 12.0 from mart_promise_gap where is_late and repeat_180 is not null and {in_w}"),
        "p_one_star_late": one(f"select avg(one_star) from mart_promise_gap where is_late and {in_w}"),
        "mean_score_late": one(f"select avg(review_score) from mart_promise_gap where is_late and {in_w}"),
        "sd_score_late": one(f"select stddev_samp(review_score) from mart_promise_gap where is_late and {in_w}"),
        "p_repeat_late": one(f"select avg(repeat_180) from mart_promise_gap where is_late and {in_w}"),
        "review_rate_late": one(f"select avg(has_review::int) from mart_promise_gap where is_late and {in_w}"),
    }
    rel = config.EXPERIMENT_MDE_RELATIVE

    # Primary: 1-star rate among reviewed late orders.
    n_primary, p_treat = n_per_arm_proportion(base["p_one_star_late"], rel)
    total_primary = 2 * n_primary
    months_primary = total_primary / base["late_reviewed_per_month"]
    # Secondary: mean review score, MDE of the same relative size on the 1-5 scale gap.
    delta_score = 0.2
    n_score = n_per_arm_mean(base["sd_score_late"], delta_score)
    # Repeat purchase: shows why it cannot be the primary metric.
    n_repeat, p_repeat_treat = n_per_arm_proportion(base["p_repeat_late"], -rel)
    months_repeat = 2 * n_repeat / base["late_first_observed_per_month"]

    table = []
    for r in [0.05, 0.10, 0.15, 0.20, 0.30]:
        n, _ = n_per_arm_proportion(base["p_one_star_late"], r)
        table.append({"relative_drop_in_one_star": r, "absolute_drop_pp": 100 * base["p_one_star_late"] * r,
                      "n_per_arm": n, "total": 2 * n,
                      "months_at_measured_volume": 2 * n / base["late_reviewed_per_month"]})
    power_table = pd.DataFrame(table)
    power_table.to_csv(config.OUTPUTS / "experiment_power.csv", index=False)

    out = {f"exp_{k}": float(v) for k, v in base.items()}
    out.update({
        "exp_mde_relative": rel, "exp_p_one_star_treat": p_treat,
        "exp_n_per_arm": n_primary, "exp_n_total": total_primary,
        "exp_months": months_primary, "exp_weeks": months_primary * 52 / 12,
        "exp_score_delta": delta_score, "exp_n_per_arm_score": n_score,
        "exp_n_per_arm_repeat": n_repeat, "exp_months_repeat": months_repeat,
        "exp_p_repeat_treat": p_repeat_treat,
        "exp_power": config.POWER, "exp_alpha": config.ALPHA,
    })
    write_doc(out, m, power_table)
    return out


def write_doc(e, m, power_table):
    pt = power_table.copy()
    pt["relative_drop_in_one_star"] = (100 * pt.relative_drop_in_one_star).round(0).astype(int).astype(str) + "%"
    pt["absolute_drop_pp"] = pt.absolute_drop_pp.round(1)
    pt["months_at_measured_volume"] = pt.months_at_measured_volume.round(1)
    text = f"""# Experiment design: proactive delay messages

Generated by `src/experiment.py`. Do not edit by hand.

**This is a design, not a run experiment. No customer was messaged and no result exists.**
Every baseline below is measured from the Olist data (12 months to {VOLUME_WINDOW[1][:7]}, exclusive).

## Why this experiment

The analysis found no sharp jump at the promise date, but a steep rise in 1-star reviews over the
first days of lateness: {100 * m['rd_one_star_day0_mean']:.1f}% on day 0, {100 * m['rd_one_star_day1_mean']:.1f}% on day 1,
{100 * m['one_star_day3']:.1f}% on day 3. From day 3 most late customers get the review survey before the parcel.
The customer is left with a broken promise and no information. A message that admits the delay and gives a
new date is cheap, and it targets exactly that gap. The data cannot estimate its effect because Olist sent no
such messages. Only an experiment can.

Options considered and not chosen as the first test:

- **Padding the delivery estimate.** Would cut late orders, but it changes what customers see at checkout
  and could lower conversion. Checkout data is not available here to size that risk.
- **Holding the survey until delivery.** Likely helps, but it changes how the primary metric is measured,
  so it should be a separate test or a policy change, not mixed into this one.

## Hypothesis

H0: sending a proactive delay message with a revised date does not change the 1-star rate of late orders.
H1: it changes it (two-sided test; the expectation is a reduction).

## Design

- **Trigger:** an order is flagged on the morning after its estimated date if it has not been delivered.
  Only flagged orders enter the experiment. Analysis compares flagged orders in each arm.
- **Treatment:** message on the day after the missed date with an apology and a revised delivery date.
- **Control:** current experience (no message).
- **Survey timing:** identical in both arms, so the metric means the same thing in both.

## Unit of randomisation

**Customer (`customer_unique_id`), hashed into two arms, 50/50.**

- Why customer and not order: a customer with two late orders should get a consistent experience, and
  repeat purchase is a customer outcome.
- Why not seller: the message is sent by Olist, not by the seller, and does not change seller behaviour.
  Randomising by seller would cut the number of independent units to a few hundred and widen the
  confidence interval for no gain.
- **Interference risk is low.** One customer's message does not change another customer's delivery or
  review. The remaining risk is operational: if customer service treats messaged customers differently,
  the effect includes that. Keep service scripts the same in both arms.

## Metrics

| Role | Metric | Baseline in the data |
|:--|:--|--:|
| Primary | 1-star rate among reviewed flagged orders | {100 * e['exp_p_one_star_late']:.1f}% |
| Secondary | Mean review score among flagged orders | {e['exp_mean_score_late']:.2f} (SD {e['exp_sd_score_late']:.2f}) |
| Secondary (long run) | Repeat purchase within 180 days, first orders | {100 * e['exp_p_repeat_late']:.1f}% |
| Guardrail | Review response rate (the message must not suppress or inflate responses) | {100 * e['exp_review_rate_late']:.1f}% |
| Guardrail | Cancellation and refund rate of flagged orders | not in data; must be logged |
| Guardrail | Customer service contacts per flagged order | not in data; must be logged |
| Guardrail | Days from estimate to delivery (the message must not change logistics) | measured per arm |

## Power and sample size

- Significance level {e['exp_alpha']:.2f} (two-sided), power {100 * e['exp_power']:.0f}%, 50/50 split.
- Minimum detectable effect: a {100 * e['exp_mde_relative']:.0f}% relative drop in the 1-star rate, from
  {100 * e['exp_p_one_star_late']:.1f}% to {100 * e['exp_p_one_star_treat']:.1f}%.
- **Required: {e['exp_n_per_arm']:,.0f} reviewed flagged orders per arm, {e['exp_n_total']:,.0f} in total.**
- Measured volume: {e['exp_late_orders_per_month']:,.0f} late orders per month, of which
  {e['exp_late_reviewed_per_month']:,.0f} are reviewed.
- **Duration at that volume: about {e['exp_months']:.1f} months ({e['exp_weeks']:.0f} weeks).** Run whole weeks
  and add time for the last reviews to come in.

Sensitivity to the effect size:

{pt.to_markdown(index=False)}

The mean review score is a more sensitive secondary metric: detecting a {e['exp_score_delta']:.1f} point change
needs {e['exp_n_per_arm_score']:,.0f} orders per arm.

**Repeat purchase cannot be the primary metric.** Detecting a {100 * e['exp_mde_relative']:.0f}% relative change
from {100 * e['exp_p_repeat_late']:.1f}% needs {e['exp_n_per_arm_repeat']:,.0f} first orders per arm, which is about
{e['exp_months_repeat']:.0f} months of late first orders at this volume, plus 180 days of follow-up. It is tracked
but not decided on.

The duration is long because Olist's 2017-2018 volume is small. At today's marketplace volumes it would
be shorter, but that cannot be computed from this data.

## Decision rule

Ship the message if the 1-star rate falls with p < {e['exp_alpha']:.2f} at the planned sample size and no
guardrail gets worse beyond its pre-set threshold. If the result is null, do not ship on a secondary metric alone.

## Pitfalls and how the design handles them

- **Peeking.** Checking the p-value every week and stopping at the first p < 0.05 inflates false positives.
  Fix the sample size above in advance, or use a sequential design with alpha spending
  (for example O'Brien-Fleming boundaries) if early looks are needed.
- **Sample ratio mismatch (SRM).** If the arms are not close to 50/50, assignment or logging is broken.
  Run a chi-square test on arm counts daily; stop and debug if p < 0.001.
- **Novelty effect.** Customers may react to a new message more at first. Compare the effect in the first
  and second half of the test, and keep monitoring after launch.
- **Trigger dilution.** Analyse only flagged orders. Including all orders would bury the effect under
  orders that were never late.
- **Outcome lag.** Reviews arrive days after the trigger. Analyse only orders whose review window has closed.
- **Seasonality.** Late rates were much higher in some months (for example around Black Friday 2017 and
  February to March 2018). Run across full weeks and report the late rate per arm.
- **Multiple metrics.** One primary metric decides. Secondary and guardrail results are read with that in mind.
"""
    (config.DOCS / "experiment_design.md").write_text(text, encoding="utf-8")
