"""Writes docs/promise_gap_results.md. Wording depends on the numbers, so it cannot overclaim."""
import pandas as pd

from src import config


def _sig(p):
    return "significant at 5%" if p < config.ALPHA else "not significant at 5%"


def pp(v):
    return f"{100 * v:+.1f} pp"


def pct(v):
    return f"{100 * v:.1f}%"


def write_doc(m):
    res = pd.read_csv(config.OUTPUTS / "rd_results.csv")
    bal = pd.read_csv(config.OUTPUTS / "rd_balance.csv")
    cv = pd.read_csv(config.OUTPUTS / "rd_bandwidth_cv.csv")
    cols = ["outcome", "spec", "h", "c", "estimate", "ci_low", "ci_high", "p_value", "n_left", "n_right"]
    h = m["rd_bandwidth"]
    rows_main = [
        ("1-star rate", pct(m["rd_one_star_control_mean_at_cutoff"]), pp(m["rd_one_star_estimate"]),
         f"{pp(m['rd_one_star_ci_low'])} to {pp(m['rd_one_star_ci_high'])}", _sig(m["rd_one_star_p_value"])),
        ("Mean review score", f"{m['rd_review_score_control_mean_at_cutoff']:.2f}",
         f"{m['rd_review_score_estimate']:+.2f}",
         f"{m['rd_review_score_ci_low']:+.2f} to {m['rd_review_score_ci_high']:+.2f}",
         _sig(m["rd_review_score_p_value"])),
        ("Repeat within 180 days", pct(m["rd_repeat_180_control_mean_at_cutoff"]), pp(m["rd_repeat_180_estimate"]),
         f"{pp(m['rd_repeat_180_ci_low'])} to {pp(m['rd_repeat_180_ci_high'])}", _sig(m["rd_repeat_180_p_value"])),
    ]
    rows_adj = [
        ("1-star rate", pct(m["rd_one_star_day0_mean"]), pct(m["rd_one_star_day1_mean"]),
         pp(m["rd_one_star_adjacent_estimate"]),
         f"{pp(m['rd_one_star_adjacent_ci_low'])} to {pp(m['rd_one_star_adjacent_ci_high'])}"),
        ("Mean review score", f"{m['rd_review_score_day0_mean']:.2f}", f"{m['rd_review_score_day1_mean']:.2f}",
         f"{m['rd_review_score_adjacent_estimate']:+.2f}",
         f"{m['rd_review_score_adjacent_ci_low']:+.2f} to {m['rd_review_score_adjacent_ci_high']:+.2f}"),
        ("Repeat within 180 days", pct(m["rd_repeat_180_day0_mean"]), pct(m["rd_repeat_180_day1_mean"]),
         pp(m["rd_repeat_180_adjacent_estimate"]),
         f"{pp(m['rd_repeat_180_adjacent_ci_low'])} to {pp(m['rd_repeat_180_adjacent_ci_high'])}"),
    ]
    t_main = pd.DataFrame(rows_main, columns=["Outcome", "Just before the line", "Jump at the line",
                                              "95% CI", "Reading"]).to_markdown(index=False)
    t_adj = pd.DataFrame(rows_adj, columns=["Outcome", "Day 0", "Day 1", "Difference", "95% CI"]
                         ).to_markdown(index=False)

    text = f"""# The promise gap: regression discontinuity results

Generated by `src/rd_report.py`. Do not edit by hand. Effects on rates are in percentage
points (pp). 95% confidence intervals use HC1 robust standard errors.

## What is being estimated

Running variable: days between the estimated delivery date and the actual delivery date.
Day 0 means delivered on the promised day. Day 1 is the first late day. The RD compares
orders just either side of that line. **This is a local effect at the promise date. It says
what happens when an order misses its promise by about one day. It does not directly
describe orders that are a week late.**

## Bandwidth

Chosen by leave-one-out cross-validation on the 1-star rate: h = {h} days per side
(candidates {cv.h.min()} to {cv.h.max()}). Robustness at {m['rd_bandwidth_low']} and {m['rd_bandwidth_high']} days.

## Main results (local linear, triangular kernel, h = {h})

{t_main}

Day 1 against day 0 directly (no slope; the local randomisation view):

{t_adj}

## How to read this

1. **There is no sharp cliff at the promise date once the trend is allowed for.** The local
   linear jump in the 1-star rate is {pp(m['rd_one_star_estimate'])} and its interval includes zero.
2. **There is a steep ramp right after it.** The 1-star rate is {pct(m['rd_one_star_day0_mean'])} on day 0,
   {pct(m['rd_one_star_day1_mean'])} on day 1, {pct(m['one_star_day2'])} on day 2, {pct(m['one_star_day3'])} on day 3
   and {pct(m['one_star_late_6plus'])} for orders 6 or more days late. The day 1 vs day 0 difference
   ({pp(m['rd_one_star_adjacent_estimate'])}) is real, but it mixes any jump with the start of that ramp.
3. **The ramp lines up with survey timing.** The share of reviews sent before the parcel arrived is
   {pct(m['review_before_delivery_day2'])} on day 2 and {pct(m['review_before_delivery_day3'])} on day 3.
   From day 3 most late customers are asked to rate an order they do not have yet.
4. **Repeat purchase shows no detectable effect.** The interval ({pp(m['rd_repeat_180_ci_low'])} to
   {pp(m['rd_repeat_180_ci_high'])}) is wide next to a baseline of {pct(m['rd_repeat_180_control_mean_at_cutoff'])}.
   The data cannot rule out zero. It also cannot rule out a loss of up to {pp(-m['rd_repeat_180_ci_low'])[1:]}.
5. **The naive comparison is far larger than the local effect.** All late vs all on-time orders: 1-star
   {pct(m['naive_one_star_on_time'])} vs {pct(m['naive_one_star_late'])}. Most of that gap comes from orders that
   are many days late, not from the act of missing the promise by a day.

## Validity checks

**Density (manipulation) check: fails.** {int(m['density_count_day_0']):,} orders arrive on day 0 and only
{int(m['density_count_day_1']):,} on day 1. The fitted count ratio at the line is {m['density_count_ratio']:.2f}
(95% CI {m['density_ratio_ci_low']:.2f} to {m['density_ratio_ci_high']:.2f}). Carriers and sellers likely push
to deliver by the promised date, so orders just on time may differ from orders just late.

**Donut check** (drop days 0 and 1): 1-star {pp(m['rd_one_star_donut_estimate'])}
(CI {pp(m['rd_one_star_donut_ci_low'])} to {pp(m['rd_one_star_donut_ci_high'])}); review score
{m['rd_review_score_donut_estimate']:+.2f} (CI {m['rd_review_score_donut_ci_low']:+.2f} to {m['rd_review_score_donut_ci_high']:+.2f});
repeat {pp(m['rd_repeat_180_donut_estimate'])} (CI {pp(m['rd_repeat_180_donut_ci_low'])} to {pp(m['rd_repeat_180_donut_ci_high'])}).
Without the days at the line, the slopes do more of the work, so the donut is noisier and leans on extrapolation.

**Placebo cutoffs** (one bandwidth either side, each using one side of the real line only): 1-star
{pp(m['rd_one_star_placebo_below_estimate'])} (p = {m['rd_one_star_placebo_below_p']:.2f}) and
{pp(m['rd_one_star_placebo_above_estimate'])} (p = {m['rd_one_star_placebo_above_p']:.2f}). No fake jumps.

**Covariate balance: partly fails.** {m['balance_n_significant']} of {m['balance_n_tested']} covariates jump at the
line at the 5% level, including promised delivery time. Orders that end up just late were, on average,
promised a longer delivery. Predicting the 1-star rate from covariates alone gives a jump of
{pp(m['balance_predicted_estimate'])} (p = {m['balance_predicted_p_value']:.3f}). That is small next to the
day 1 to day 3 ramp, but it means the two sides are not perfectly comparable.

**Review selection:** the chance of leaving a review does not jump ({pp(m['rd_has_review_estimate'])},
p = {m['rd_has_review_p_value']:.2f}).

## All estimates

{res[cols].round(4).to_markdown(index=False)}

## Covariate balance

{bal[['covariate', 'estimate', 'ci_low', 'ci_high', 'p_value']].round(4).to_markdown(index=False)}

## Bandwidth cross-validation

{cv.round(6).to_markdown(index=False)}
"""
    (config.DOCS / "promise_gap_results.md").write_text(text, encoding="utf-8")
