"""Writes powerbi/POWERBI_BUILD_GUIDE.md with expected values filled in from the metrics."""
from src import config


def write(m):
    p = lambda k: f"{100 * m[k]:.1f}%"
    text = f"""# Power BI build guide

Generated by `src/powerbi_guide.py`. Build the report in Power BI Desktop from the CSVs in
`powerbi/data/` (created by `python run_all.py`). Expected values come from `outputs/metrics.json`,
so you can check each visual against the Python results.

## 1. Load the data

1. Home > Get data > Text/CSV. Load every file in `powerbi/data/`.
2. In Power Query, check types:
   - Dates: `dim_date[date]`, `dim_customer[cohort_month]`, `dim_customer[first_purchase_date]`,
     `dim_seller[first_sale_date]`, `dim_seller[seller_cohort_month]`, `agg_*_cohorts[cohort_month]`.
   - Whole numbers: all `*_key` columns that hold dates (`purchase_date_key`, `date_key`), all `is_*` flags,
     `days_late`, `promised_days`, `review_score`, `one_star`, `repeat_180`.
   - Decimal: values in R$, hours, rates, estimates.
   - True/False: `agg_customer_cohorts[is_observed]`, `agg_seller_cohorts[is_observed]`.
3. Close and apply.

## 2. Model (star schema)

Model view. Create these relationships, all many-to-one, single direction, from fact to dimension:

| From | To |
|:--|:--|
| `fact_orders[customer_key]` | `dim_customer[customer_key]` |
| `fact_orders[seller_key]` | `dim_seller[seller_key]` |
| `fact_orders[category_key]` | `dim_category[category_key]` |
| `fact_orders[purchase_date_key]` | `dim_date[date_key]` |

Then select `dim_date`, Table tools > Mark as date table, using `dim_date[date]`.
Leave the `agg_*` tables unrelated. They are pre-computed outputs used on their own visuals.

Why a star: one fact table at order grain, small dimensions around it. Filters flow from dimensions to
the fact, which keeps DAX simple and fast.

## 3. Measures

Create a blank table `_Measures` (Home > Enter data > OK), then add each measure from
`powerbi/measures.dax`. Format rates as percentage with 1 decimal.

## 4. Pages

### Page 1: Funnel

- Funnel visual: values `Orders`, `Approved Orders`, `Shipped Orders`, `Delivered Orders`, `Reviewed Orders`.
- Cards: `Conv Purchased to Delivered` (expect {p('funnel_conv_purchased_to_delivered')}),
  `Conv Delivered to Reviewed` (expect {p('funnel_conv_delivered_to_reviewed')}),
  `Median Hours Ship to Deliver` (expect {m['funnel_median_h_ship_to_deliver']:.1f}).
- Line chart: axis `dim_date[year_month]`, values `Conv Purchased to Delivered`.
- Bar chart: axis `dim_category[category_name]`, values `Orders`, tooltip `Conv Purchased to Delivered`. Top N = 15.
- Seller funnel: clustered bar from `agg_seller_funnel`, filter `dimension = overall`, values
  `Seller Leads`, `Seller Closed Deals`, `Seller First Sales`, `Seller Still Selling 90d`.
  Expect {m['seller_leads']:,.0f} leads, {m['seller_closed']:,.0f} closed, {m['seller_first_sale']:,.0f} first sales.
- Table from `agg_seller_funnel` filtered to `dimension = lead_origin` with the three conversion measures.
- Title: "Most orders arrive; most closed sellers never sell".

### Page 2: Cohorts

- Cards: `Repeat Rate All Time` (expect {p('repeat_rate_all_time')}), `Repeat Rate 180d` (expect {p('repeat_rate_180d')}),
  `Customers` (expect {m['customers']:,.0f}).
- Matrix (the triangle): rows `agg_customer_cohorts[cohort_month]`, columns `agg_customer_cohorts[month_number]`,
  values `Cohort Retention`. Conditional formatting > background color > gradient, white to blue.
  Filter `month_number` greater than 0. Blank cells are months the data cannot see yet.
- Line chart: axis `agg_customer_cohorts[month_number]`, values `Cohort Retention`. Expect month 1 = {p('cust_retention_m1')}.
- Second line chart (separate, not a second axis): `agg_seller_cohorts[month_number]` vs `Seller Activity Rate`.
  Expect month 1 = {p('seller_activity_m1')}.
- Title: "Customers rarely return; sellers mostly stay".

### Page 3: Promise Gap

- Add a calculated column for a clean axis:
  `Days Late Capped = IF ( ISBLANK ( fact_orders[days_late] ), BLANK (), MAX ( -15, MIN ( 15, fact_orders[days_late] ) ) )`
- Column chart: axis `Days Late Capped`, values `One Star Rate`. Add a constant line at 0.5 (the promise date).
  Expect day 0 = {p('rd_one_star_day0_mean')}, day 1 = {p('rd_one_star_day1_mean')}, day 3 = {p('one_star_day3')}.
- Line chart: same axis, `Review Before Delivery Rate`. Expect day 3 = {p('review_before_delivery_day3')}.
- Cards: `Late Rate` (expect {p('late_rate')}), `One Star Rate` filtered to `is_late = 1` (expect {p('naive_one_star_late')}).
- Table from `agg_rd_results`: outcome, spec, h, estimate, ci_low, ci_high, p_value.
  Slicer on `outcome`. Expect the main 1-star estimate to be {100 * m['rd_one_star_estimate']:+.1f} pp.
- Text box: "Local effect at the promise date. Not the effect of being a week late."

### Page 4: Experiment Plan

- Cards: required orders per arm {m['exp_n_per_arm']:,.0f}, duration {m['exp_months']:.1f} months
  (from `agg_experiment_power` filtered to `relative_drop_in_one_star = 0.1`).
- Line chart: `agg_experiment_power[relative_drop_in_one_star]` vs `Required Orders Per Arm`.
- Table from `agg_sizing`: scenario, scope, effect_pp, loss_per_quarter.
- Text box with hypothesis, unit, primary metric and guardrails from `docs/experiment_design.md`.
- Text box: "Design only. Not a run experiment."

## 5. Finish

- One theme for all pages. Blue for on-time or baseline, orange for late or treatment.
- Save as `powerbi/the_promise_gap.pbix`. Export each page to PNG into `docs/screenshots/`.
"""
    (config.POWERBI / "POWERBI_BUILD_GUIDE.md").write_text(text, encoding="utf-8")
