"""Section 2: build staging, intermediate and mart layers, export the exclusion log."""
from src import config
from src.db import build, connect, register_raw


def export_exclusions(con):
    ex = con.execute("select * from int_exclusions order by step").df()
    ex.to_csv(config.OUTPUTS / "exclusions.csv", index=False)
    window = con.execute("select * from int_data_window").df()
    window.to_csv(config.OUTPUTS / "data_window.csv", index=False)
    table = ex.astype(object).where(ex.notna(), "").to_markdown(index=False)
    text = f"""# Exclusions

Generated by `src/model.py` from `sql/intermediate/05_int_exclusions.sql`. Do not edit by hand.

Each analysis sample starts from the analysis grain (one row per delivered order)
or from the customer table. `rows_removed` is the number of rows dropped by that step.

Observation window: data ends on {window.data_end[0].date()}. The last fully observed month
starts on {window.last_complete_month[0].date()}.

{table}

Why each step exists:

- Steps 2 and 3: the promise gap needs a real delivery date. Status alone is not enough
  because a few "delivered" orders have no delivery timestamp.
- Step 4: review score and the 1-star rate can only be measured when a review exists.
- Step 5: the repeat outcome uses first orders only. A late first order is the cleanest test of
  "does a broken promise stop a new customer coming back". Later orders come from customers
  who already chose to return, which would bias the comparison.
- Step 6: right censoring. An order placed less than {config.REPEAT_WINDOW_DAYS} days before the
  data ends has not had the chance to be followed by a repeat purchase. Counting it as
  "no repeat" would understate the rate.
- Step 8: 2016 has very few orders and a two-month gap, so cohorts start in {config.COHORT_START[:7]}.
  Customers whose first purchase was in 2016 are still used to decide who is new in 2017.
"""
    (config.DOCS / "exclusions.md").write_text(text, encoding="utf-8")
    return ex


def main(con=None):
    con = con or connect()
    register_raw(con)
    build(con)
    return export_exclusions(con)


if __name__ == "__main__":
    print(main().to_string())
